def get_x_calibration_lut(mode):
    """Return a validated immutable LUT for the selected calibration mode."""
    if mode == X_CALIBRATION_PINHOLE:
        return X_POSITION_CM_X10000
    if mode == X_CALIBRATION_MEASURED:
        return X_POSITION_CM_MEASURED_X10000
    raise ValueError(
        "unknown X calibration {}; use {} or {}".format(
            mode,
            X_CALIBRATION_MEASURED,
            X_CALIBRATION_PINHOLE,
        )
    )


def x_center_scale(lut=X_POSITION_CM_X10000):
    """Return the centered physical Y scale associated with an X LUT."""
    if lut is X_POSITION_CM_X10000:
        return Y_CM_PER_PIXEL
    return (
        lut[int(IMAGE_CENTER_X_PX) + 1]
        - lut[int(IMAGE_CENTER_X_PX) - 1]
    ) / (2.0 * X_LUT_SCALE)


def _clamp_pixel(value):
    value = float(value)
    if value <= 0.0:
        return 0.0
    if value >= X_LUT_LAST_INDEX:
        return float(X_LUT_LAST_INDEX)
    return value


def x_position_and_scale(pixel_x, lut=X_POSITION_CM_X10000):
    """Return physical X in cm and local cm/pixel at an image X coordinate."""
    pixel_x = _clamp_pixel(pixel_x)
    left_index = int(pixel_x)
    if left_index >= X_LUT_LAST_INDEX:
        left_index = X_LUT_LAST_INDEX - 1
        fraction = 1.0
    else:
        fraction = pixel_x - left_index
    left_value = lut[left_index]
    step_value = lut[left_index + 1] - left_value
    return (
        (left_value + step_value * fraction) / X_LUT_SCALE,
        step_value / X_LUT_SCALE,
    )


def x_pixel_for_position_cm(position_cm, lut=X_POSITION_CM_X10000):
    """Return the subpixel image X for a physical X using the same LUT."""
    target = float(position_cm) * X_LUT_SCALE
    if target <= lut[0]:
        return 0.0
    if target >= lut[X_LUT_LAST_INDEX]:
        return float(X_LUT_LAST_INDEX)

    low = 0
    high = X_LUT_LAST_INDEX
    while low + 1 < high:
        middle = (low + high) // 2
        if lut[middle] <= target:
            low = middle
        else:
            high = middle

    left_value = lut[low]
    step_value = lut[high] - left_value
    return low + (target - left_value) / step_value


def y_position_cm(pixel_y, cm_per_pixel=Y_CM_PER_PIXEL):
    """Return linearized physical Y in cm around the optical center."""
    return (float(pixel_y) - IMAGE_CENTER_Y_PX) * float(cm_per_pixel)
